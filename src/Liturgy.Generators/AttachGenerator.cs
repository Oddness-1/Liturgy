using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Liturgy.Generators;

/// <summary>
/// Puts Liturgy's attach attribute on every Godot class in an assembly that references Liturgy, the way Godot's own
/// generator adds <c>[ScriptPath]</c>. Godot builds a script class's attributes when it loads the script, and the
/// first time that happens with the scene tree in place, the attribute attaches Liturgy. This replaces the addon and
/// autoload Liturgy used to need.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class AttachGenerator : IIncrementalGenerator
{
    private const string LITURGY_ASSEMBLY = "Liturgy";
    private const string GODOT_NAMESPACE = "Godot";
    private const string GODOT_OBJECT_NAME = "GodotObject";
    private const string ATTACH_ATTRIBUTE = "global::Liturgy.Internal.Attach";

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var referencesLiturgy = context.CompilationProvider
            .Select(static (compilation, _) => compilation.ReferencedAssemblyNames.Any(static identity => identity.Name == LITURGY_ASSEMBLY));

        var godotClasses = context.SyntaxProvider
            .CreateSyntaxProvider(
                // A Godot class has a base list on at least one of its parts, so parts without one need no semantic check.
                static (node, _) => node is ClassDeclarationSyntax { Parent: BaseNamespaceDeclarationSyntax or CompilationUnitSyntax, BaseList: not null } declaration
                                    && declaration.Modifiers.Any(SyntaxKind.PartialKeyword),
                static (syntax, token) => syntax.SemanticModel.GetDeclaredSymbol((ClassDeclarationSyntax)syntax.Node, token))
            .Where(static type => type is not null && IsGodotObject(type))
            .Select(static (type, _) => Stamp(type!))
            .Collect();

        context.RegisterSourceOutput(referencesLiturgy.Combine(godotClasses), static (production, input) =>
        {
            var (references, stamps) = input;
            if (!references || stamps.IsEmpty) return;

            var source = new StringBuilder("// <auto-generated/>\n");
            foreach (var group in stamps.Distinct().GroupBy(static stamp => stamp.Namespace).OrderBy(static group => group.Key))
            {
                var indent = group.Key.Length == 0 ? "" : "    ";
                if (indent.Length > 0) source.Append($"\nnamespace {group.Key}\n{{\n");
                foreach (var stamp in group.OrderBy(static stamp => stamp.Declaration)) source.Append($"{indent}{stamp.Declaration}\n");
                if (indent.Length > 0) source.Append("}\n");
            }

            production.AddSource("Liturgy.Attach.g.cs", source.ToString());
        });
    }

    private static bool IsGodotObject(INamedTypeSymbol type)
    {
        for (var current = type.BaseType; current is not null; current = current.BaseType)
        {
            if (current is { Name: GODOT_OBJECT_NAME, ContainingNamespace: { Name: GODOT_NAMESPACE, ContainingNamespace.IsGlobalNamespace: true } }) return true;
        }

        return false;
    }

    private static (string Namespace, string Declaration) Stamp(INamedTypeSymbol type)
    {
        var typeParameters = type.TypeParameters.IsEmpty ? "" : $"<{string.Join(", ", type.TypeParameters.Select(static parameter => parameter.Name))}>";
        var space = type.ContainingNamespace.IsGlobalNamespace ? "" : type.ContainingNamespace.ToDisplayString();
        return (space, $"[{ATTACH_ATTRIBUTE}] partial class {type.Name}{typeParameters} {{ }}");
    }
}
