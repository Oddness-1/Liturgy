using System.Linq;
using Microsoft.CodeAnalysis;

namespace Liturgy.Generators;

/// <summary>
/// Emits a module initializer into every assembly that references Liturgy. It runs the first time any code in
/// that assembly executes, which in a Godot game is before /root enters the tree, and attaches Liturgy there.
/// This replaces the addon and autoload Liturgy used to need.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class AttachGenerator : IIncrementalGenerator
{
    private const string LITURGY_ASSEMBLY = "Liturgy";

    private const string SOURCE = """
        // <auto-generated/>
        #pragma warning disable CA2255

        namespace Liturgy.Generated
        {
            internal static class LiturgyAttach
            {
                [global::System.Runtime.CompilerServices.ModuleInitializer]
                internal static void Attach() => global::Liturgy.Internal.Startup.Attach();
            }
        }
        """;

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var referencesLiturgy = context.CompilationProvider
            .Select(static (compilation, _) => compilation.ReferencedAssemblyNames.Any(static identity => identity.Name == LITURGY_ASSEMBLY));

        context.RegisterSourceOutput(referencesLiturgy, static (production, references) =>
        {
            if (references) production.AddSource("Liturgy.Attach.g.cs", SOURCE);
        });
    }
}
